export function getLocalizedCategoryName(
  category: Pick<Category, 'slug' | 'name'>,
  locale: string,
) {
  const normalizedLocale: SupportedLocale = locale === 'th' ? 'th' : 'en';
  return (
    categoryCopy[category.slug as keyof typeof categoryCopy]?.[
      normalizedLocale
    ] ?? category.name
  );
}

type ProductLike = Product | ProductDetail;

export function getLocalizedProduct<T extends ProductLike>(
  product: T,
  locale: string,
) {
  const normalizedLocale: SupportedLocale = locale === 'th' ? 'th' : 'en';

  if (normalizedLocale === 'en') {
    return {
      ...product,
      category: {
        ...product.category,
        name: getLocalizedCategoryName(product.category, normalizedLocale),
      },
    };
  }

  return {
    ...product,
    category: {
      ...product.category,
      name: getLocalizedCategoryName(product.category, normalizedLocale),
    },
  } as T;
}
